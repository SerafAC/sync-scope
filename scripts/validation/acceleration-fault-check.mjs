#!/usr/bin/env node
// Developer acceptance harness for automatic graphics fallback (feature 008,
// contracts/acceleration.md "Automated runtime failure injection"). It is not
// an app feature or a production fault switch: it drives the existing
// validator's start/healthcheck/stop lifecycle through a private SDK overlay
// whose generated emulator wrapper rejects only this run's token-scoped
// candidate launches. The installed SDK, AVDs, parent environment and public
// runner CLI are never modified, and its results never become ranking or
// before/after timing samples.
import {createHash, randomBytes} from 'node:crypto';
import {spawn} from 'node:child_process';
import {createReadStream} from 'node:fs';
import {lstat, mkdir, mkdtemp, readdir, readFile, rm, stat, symlink, writeFile} from 'node:fs/promises';
import {homedir, tmpdir} from 'node:os';
import {join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

import {REASONS, STATES} from './performance-acceleration.mjs';

const CASES = ['hardware-fallback', 'all-options-fail'];
const CANDIDATE = /^(?:host-(?:intel|nvidia)-[1-9]|software-(?:swiftshader|software|lavapipe|swangle))$/;
const GPU_REQUESTS = ['host', 'swiftshader', 'software', 'lavapipe', 'swangle'];
const GRAPHICS = ['hardware', 'software'];
const BACKENDS = ['host', 'swiftshader', 'software', 'llvmpipe', 'lavapipe', 'softpipe', 'swangle'];
const CPUS = ['kvm', 'tcg'];
const VULKAN = ['enabled', 'absent', 'unknown'];
const RECEIPTS = ['acquired', 'borrowed', 'released'];
const INJECTED_STATUS = 70;

function usage() { throw new Error('usage'); }
export function parseArgs(argv) {
  const apis = [];
  let caseName = null, reportDir = null;
  for (let i = 0; i < argv.length; i += 2) {
    const [flag, value] = [argv[i], argv[i + 1]];
    if (value === undefined || value.startsWith('--')) { usage(); }
    if (flag === '--api' && ['31', '36'].includes(value) && !apis.includes(Number(value))) { apis.push(Number(value)); }
    else if (flag === '--case' && caseName === null && CASES.includes(value)) { caseName = value; }
    else if (flag === '--report-dir' && reportDir === null && value) { reportDir = value; }
    else { usage(); }
  }
  if (!apis.length || !caseName || !reportDir) { usage(); }
  return {apis, caseName, reportDir};
}

const quote = value => {
  if (/['\n\0]/.test(value)) { throw new Error('unsafe-path'); }
  return `'${value}'`;
};
// The wrapper forwards every probe (no -avd) and every launch without this
// run's token or for another AVD to the real emulator, with the real SDK root
// restored and the token removed. Only a matching candidate start is rejected.
export function wrapperScript({realSdk, token, avd, caseName, injections}) {
  if (!/^[a-f0-9]{32}$/.test(token) || !/^dependency_api(?:31|36)$/.test(avd) || !CASES.includes(caseName)) {
    throw new Error('invalid-wrapper');
  }
  const reject = caseName === 'all-options-fail' ? '*' : 'host';
  return `#!/bin/sh
# Generated by acceleration-fault-check.mjs for one private run; removed after it.
inject=0
gpu=
if [ "\${SYNCSCOPE_FAULT_TOKEN:-}" = '${token}' ]; then
  avd=
  previous=
  for argument in "$@"; do
    case "$previous" in -avd) avd=$argument ;; -gpu) gpu=$argument ;; esac
    previous=$argument
  done
  if [ "$avd" = '${avd}' ] && [ -n "$gpu" ]; then
    case "$gpu" in ${GPU_REQUESTS.join('|')}) ;; *) gpu=other ;; esac
    case "$gpu" in ${reject}) inject=1 ;; esac
  fi
fi
if [ "$inject" = 1 ]; then
  printf '%s\\n' "$gpu" >>${quote(injections)}
  printf '%s\\n' "fault-check: injected launch failure for -gpu $gpu" >&2
  exit ${INJECTED_STATUS}
fi
unset SYNCSCOPE_FAULT_TOKEN
ANDROID_HOME=${quote(realSdk)}
ANDROID_SDK_ROOT=${quote(realSdk)}
export ANDROID_HOME ANDROID_SDK_ROOT
exec ${quote(join(realSdk, 'emulator/emulator'))} "$@"
`;
}

// A private SDK root: symlinks to the unchanged real tools/images, plus a
// generated emulator entry. Nothing is written inside the real SDK.
export async function createOverlay({realSdk, root, token, avd, caseName}) {
  quote(root); quote(realSdk);
  await mkdir(root, {mode: 0o700});
  const sdk = join(root, 'sdk'), injections = join(root, 'injections');
  await mkdir(join(sdk, 'emulator'), {recursive: true, mode: 0o700});
  for (const entry of await readdir(realSdk)) {
    if (entry !== 'emulator') { await symlink(join(realSdk, entry), join(sdk, entry)); }
  }
  for (const entry of await readdir(join(realSdk, 'emulator'))) {
    if (entry !== 'emulator') { await symlink(join(realSdk, 'emulator', entry), join(sdk, 'emulator', entry)); }
  }
  await writeFile(injections, '', {mode: 0o600});
  await writeFile(join(sdk, 'emulator/emulator'), wrapperScript({realSdk, token, avd, caseName, injections}),
    {mode: 0o700});
  return {sdk, injections};
}

// Planned candidates that were never launched stay "discovered" in the
// validator record; only attempted candidates are evidence here.
export function sanitizeAttempts(attempts) {
  return (Array.isArray(attempts) ? attempts : []).filter(a => a?.state !== 'discovered').map(a => {
    const v = a?.verification ?? {};
    return {
      candidateId: CANDIDATE.test(a?.candidateId ?? '') ? a.candidateId : 'unknown',
      state: STATES.includes(a?.state) ? a.state : 'unknown',
      reason: a?.reason === null || a?.reason === undefined ? null : REASONS.includes(a.reason) ? a.reason : 'unknown',
      backend: BACKENDS.includes(v.backend) ? v.backend : null,
      vulkan: VULKAN.includes(v.vulkan) ? v.vulkan : null,
    };
  });
}

const exists = path => lstat(path).then(() => true, () => false);
const readJson = path => readFile(path, 'utf8').then(JSON.parse, () => null);
async function digestFile(path) {
  const hash = createHash('sha256');
  try {
    for await (const chunk of createReadStream(path)) { hash.update(chunk); }
    return hash.digest('hex');
  } catch { return null; }
}
async function sdkIdentity(sdk) {
  const top = await readdir(sdk).catch(() => []), emulator = await readdir(join(sdk, 'emulator')).catch(() => []);
  const s = await stat(join(sdk, 'emulator/emulator')).catch(() => null);
  return JSON.stringify([top.sort(), emulator.sort(), s && [s.size, s.mtimeMs, s.mode], await digestFile(join(sdk, 'emulator/emulator'))]);
}
async function avdIdentity(avdHome, api) {
  const avd = `dependency_api${api}`;
  return JSON.stringify([await digestFile(join(avdHome, `${avd}.ini`)), await digestFile(join(avdHome, `${avd}.avd/config.ini`))]);
}
async function readReceipt(path) {
  const value = (await readFile(path, 'utf8').catch(() => '')).trim();
  return RECEIPTS.includes(value) ? value : 'missing';
}
const actualOf = (attempts, metadata) => {
  const selected = attempts.find(a => a.state === 'selected');
  if (!selected) { return null; }
  // The guest's actual graphics kind comes from the runtime metadata; the
  // verified backend and observed Vulkan state from the selected attempt.
  return {cpu: CPUS.includes(metadata?.cpu) ? metadata.cpu : 'unknown',
    graphics: GRAPHICS.includes(metadata?.graphics) ? metadata.graphics : 'unknown',
    backend: selected.backend, vulkan: selected.vulkan};
};

async function runApi(api, {caseName, reportDir, claimToken}, deps) {
  const record = {api, expected: caseName === 'hardware-fallback' ? 'software-fallback' : 'exhaustion',
    validatorExit: null, result: 'failed', injected: [], attempts: [], actual: null, healthy: null,
    cleanup: {stateRemoved: false, receipt: 'missing', survivors: 0, foreignPreserved: false, overlayRemoved: false},
    unchanged: {sdk: false, avd: false}};
  const state = deps.stateDir(`api${api}`);
  const before = {sdk: await sdkIdentity(deps.realSdk), avd: await avdIdentity(deps.avdHome, api),
    processes: (await deps.processes()).filter(p => p.api === api)};
  const diagnostics = join(reportDir, 'diagnostics.private', `api${api}`);
  await mkdir(diagnostics, {recursive: true, mode: 0o700});
  const root = await mkdtemp(join(deps.tempRoot, 'cloud-sync-checker-fault-'));
  const receipt = join(root, 'receipt');
  let fatal = null, acquired = false, stopped = false, env = null, metadata = null, liveAttempts = null;
  try {
    if (await exists(state)) { throw new Error('validator-state-exists'); }
    const token = randomBytes(16).toString('hex');
    const overlay = await createOverlay({realSdk: deps.realSdk, root: join(root, 'overlay'), token,
      avd: `dependency_api${api}`, caseName});
    record.injectionsPath = overlay.injections;
    const inherited = {...deps.env};
    for (const key of ['ANDROID_SDK_ROOT', 'SYNCSCOPE_GRAPHICS_CANDIDATE', 'SYNCSCOPE_GRAPHICS_PIN',
      'SYNCSCOPE_INVOCATION_MODE_FILE', 'SYNCSCOPE_FAULT_TOKEN']) { delete inherited[key]; }
    env = {...inherited, ANDROID_HOME: overlay.sdk, SYNCSCOPE_GRAPHICS_PROFILE: 'auto', SYNCSCOPE_FAULT_TOKEN: token,
      SYNCSCOPE_INVOCATION_TOKEN: claimToken, SYNCSCOPE_RESOURCE_RECEIPT: receipt,
      SYNCSCOPE_PERFORMANCE_DIR: diagnostics};
    deps.checkAborted?.();
    record.validatorExit = await deps.validator('start', api, env);
    acquired = await readReceipt(receipt) === 'acquired';
    deps.checkAborted?.();
    if (acquired) {
      liveAttempts = (await readJson(join(state, 'acceleration.private.json')))?.attempts ?? null;
      metadata = await readJson(join(state, 'metadata.private.json'));
      if (caseName === 'hardware-fallback' && record.validatorExit === 0) {
        record.healthy = await deps.validator('healthcheck', api, env) === 0;
      }
    }
  } catch (error) {
    fatal = error;
  } finally {
    if (acquired && env) {
      stopped = true;
      await deps.validator('stop', api, env).catch(() => null);
    }
    const retained = await readJson(join(diagnostics, 'raw', `validator-${api}`, 'acceleration.private.json'));
    const leftover = await readJson(join(state, 'acceleration.private.json'));
    record.attempts = sanitizeAttempts(retained?.attempts ?? leftover?.attempts ?? liveAttempts);
    record.actual = actualOf(record.attempts, metadata);
    if (record.injectionsPath) {
      const lines = (await readFile(record.injectionsPath, 'utf8').catch(() => '')).split('\n').filter(Boolean);
      record.injected = lines.map(line => [...GPU_REQUESTS, 'other'].includes(line) ? line : 'other');
    }
    delete record.injectionsPath;
    record.cleanup.receipt = await readReceipt(receipt);
    await rm(root, {recursive: true, force: true});
    record.cleanup.overlayRemoved = !await exists(root);
    record.cleanup.stateRemoved = !await exists(state);
    const after = (await deps.processes()).filter(p => p.api === api);
    const known = new Set(before.processes.map(p => p.pid)), now = new Set(after.map(p => p.pid));
    record.cleanup.survivors = after.filter(p => !known.has(p.pid)).length;
    record.cleanup.foreignPreserved = before.processes.every(p => now.has(p.pid));
    record.unchanged = {sdk: await sdkIdentity(deps.realSdk) === before.sdk,
      avd: await avdIdentity(deps.avdHome, api) === before.avd};
  }
  const c = record.cleanup;
  const clean = c.stateRemoved && c.receipt === 'released' && c.survivors === 0 && c.foreignPreserved &&
    c.overlayRemoved && record.unchanged.sdk && record.unchanged.avd;
  const hosts = record.attempts.filter(a => a.candidateId.startsWith('host-'));
  const software = record.attempts.filter(a => a.candidateId.startsWith('software-'));
  if (fatal || !clean) {
    record.result = 'failed';
  } else if (caseName === 'hardware-fallback') {
    const selected = record.attempts.find(a => a.state === 'selected');
    const injectedHosts = record.injected.filter(g => g === 'host').length;
    if (!hosts.length || !software.length) {
      // No exposed host route, or no usable software continuation: the
      // required demonstration was not exercised, which is not success.
      record.result = 'incomplete';
    } else {
      record.result = record.validatorExit === 0 && stopped && record.healthy === true &&
        selected?.candidateId.startsWith('software-') && record.actual?.graphics === 'software' &&
        record.actual?.cpu === 'kvm' && hosts.every(a => a.state === 'boot-failed') &&
        injectedHosts === hosts.length && record.injected.length === injectedHosts ? 'passed' : 'failed';
    }
  } else {
    record.result = record.validatorExit === 1 && !acquired && record.attempts.length > 0 &&
      record.attempts.every(a => a.state === 'boot-failed') &&
      record.injected.length === record.attempts.length ? 'passed' : 'failed';
  }
  return {record, fatal};
}

export async function runFaultCheck({apis, caseName, reportDir}, deps) {
  const output = join(reportDir, 'fault-check.json');
  if (await exists(output)) { throw new Error('evidence-exists'); }
  await mkdir(reportDir, {recursive: true, mode: 0o700});
  const claimToken = deps.claimToken ?? randomBytes(16).toString('hex');
  const records = [];
  for (const api of apis) {
    const {record, fatal} = await runApi(api, {caseName, reportDir, claimToken}, deps);
    records.push(record);
    if (fatal) { break; }
  }
  const result = records.length === apis.length && records.every(r => r.result === 'passed') ? 'passed' :
    records.some(r => r.result === 'failed') || records.length !== apis.length ? 'failed' : 'incomplete';
  // Fault-injection evidence only: never a ranking input or a timing sample.
  const evidence = {schemaVersion: 1, case: caseName, result, rankingUse: false, timingSamples: 0, apis: records};
  await writeFile(output, `${JSON.stringify(evidence, null, 2)}\n`, {mode: 0o600, flag: 'wx'});
  return result === 'passed' ? 0 : 1;
}

// ---- production boundaries -------------------------------------------------

function stateDir(name) {
  const root = process.env.SYNCSCOPE_VALIDATION_STATE_DIR;
  if (!root) { return `/tmp/cloud-sync-checker-${name}`; }
  if (!root.startsWith('/tmp/cloud-sync-checker-') || resolve(root) !== root) { throw new Error('invalid-state-dir'); }
  return join(root, name);
}
async function avdProcesses() {
  const found = [];
  for (const pid of await readdir('/proc').catch(() => [])) {
    if (!/^\d+$/.test(pid)) { continue; }
    const argv = (await readFile(`/proc/${pid}/cmdline`, 'utf8').catch(() => '')).split('\0');
    const avd = argv[argv.indexOf('-avd') + 1] ?? '';
    const match = argv.includes('-avd') && avd.match(/^dependency_api(31|36)$/);
    if (match) { found.push({pid: Number(pid), api: Number(match[1])}); }
  }
  return found;
}
// The same full-invocation claim android-flow.sh takes (flock on the stable
// invocation.lock inode), held by a helper whose stdin is this process: it
// ends, and the claim is released, when this harness exits for any reason.
async function acquireClaim(lock) {
  const info = await lstat(lock).catch(() => null);
  if (info && (!info.isFile() || info.uid !== process.getuid())) { throw new Error('unsafe-lock'); }
  if (!info) { await writeFile(lock, '', {mode: 0o600, flag: 'a'}); }
  const holder = spawn('flock', ['-n', '-E', '75', lock, 'sh', '-c', 'echo claimed; exec cat >/dev/null'],
    {stdio: ['pipe', 'pipe', 'ignore']});
  const claimed = await new Promise(done => {
    holder.stdout.once('data', chunk => done(String(chunk).startsWith('claimed')));
    holder.once('exit', () => done(false));
    holder.once('error', () => done(false));
  });
  if (!claimed) { holder.kill('SIGKILL'); return null; }
  return () => { holder.stdin.end(); };
}

async function main() {
  let options;
  try { options = parseArgs(process.argv.slice(2)); }
  catch {
    console.error('Usage: acceleration-fault-check.mjs --api <31|36> [--api <31|36>] ' +
      '--case <hardware-fallback|all-options-fail> --report-dir <directory>');
    process.exit(64);
  }
  const repo = fileURLToPath(new URL('../../', import.meta.url));
  const realSdk = process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT || join(homedir(), 'Android/Sdk');
  const release = await acquireClaim(stateDir('invocation.lock'));
  if (!release) { console.error('Another validation invocation is active.'); process.exit(1); }
  let aborted = null, child = null;
  for (const signal of ['SIGINT', 'SIGTERM', 'SIGHUP']) {
    process.on(signal, () => { aborted ??= signal; child?.kill('SIGTERM'); });
  }
  const validator = (action, api, env) => new Promise((done, fail) => {
    const log = join(env.SYNCSCOPE_PERFORMANCE_DIR, `validator-${action}.private.log`);
    child = spawn(join(repo, 'scripts/validation/android-validator.sh'), [action, '--api', String(api),
      '--avd', `dependency_api${api}`, '--state', stateDir(`api${api}`),
      '--exclusive-lock', stateDir('validator.lock')], {env, stdio: ['ignore', 'pipe', 'pipe']});
    const chunks = [];
    child.stdout.on('data', c => chunks.push(c)); child.stderr.on('data', c => chunks.push(c));
    child.once('error', fail);
    child.once('close', async (code, signal) => {
      child = null;
      await writeFile(log, Buffer.concat(chunks), {mode: 0o600, flag: 'a'}).catch(() => {});
      done(code ?? (signal ? 128 : 1));
    });
  });
  let status = 1;
  try {
    status = await runFaultCheck(options, {validator, realSdk, stateDir, processes: avdProcesses, tempRoot: tmpdir(),
      avdHome: process.env.ANDROID_AVD_HOME || join(homedir(), '.android/avd'), env: process.env,
      checkAborted: () => { if (aborted) { throw new Error('interrupted'); } }});
    const evidence = JSON.parse(await readFile(join(options.reportDir, 'fault-check.json'), 'utf8'));
    for (const a of evidence.apis) {
      console.log(`API ${a.api}: ${a.result} (validator exit ${a.validatorExit}, injected ${a.injected.join(',') || 'none'}, ` +
        `selected ${a.attempts.find(x => x.state === 'selected')?.candidateId ?? 'none'})`);
    }
    console.log(`${options.caseName}: ${evidence.result}`);
  } catch (error) {
    console.error(`Fault check failed: ${error.message}`);
  } finally {
    release();
  }
  process.exit(aborted ? 130 : status);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) { await main(); }
